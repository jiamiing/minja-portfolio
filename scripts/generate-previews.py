"""Regenerate recognizable WebP previews and the URL manifest: python3 scripts/generate-previews.py (Pillow required)."""
from pathlib import Path
from PIL import Image,ImageStat,ImageFilter
import hashlib,io,json
root=Path(__file__).resolve().parents[1]
previews={};sizes=[];originals=[]
output=root/'assets'/'previews';output.mkdir(exist_ok=True)
for source in sorted((root/'assets').glob('*.webp')):
    if source.stem.endswith('-sm'):continue
    with Image.open(source) as original:
        image=original.convert('RGB')
        limit=(1024,512) if source.stem=='garden-panorama' else (768,768) if source.stem=='hero' else (512,768)
        image.thumbnail(limit,Image.Resampling.LANCZOS)
        image=image.filter(ImageFilter.GaussianBlur(.25))
        data=io.BytesIO();image.save(data,format='WEBP',quality=50,method=6)
        color=tuple(round(v) for v in ImageStat.Stat(image.resize((1,1))).mean)
        (output/source.name).write_bytes(data.getvalue())
        digest=hashlib.sha256(data.getvalue()).hexdigest()[:10]
        previews[source.stem]={'src':f'assets/previews/{source.name}?v={digest}','width':image.width,'height':image.height,'bytes':len(data.getvalue()),'color':'#'+''.join(f'{v:02x}' for v in color)}
        sizes.append(len(data.getvalue()));originals.append(source.stat().st_size)
(root/'previews.js').write_text('// Generated by scripts/generate-previews.py. Preview files are requested only as needed.\nexport const previews = '+json.dumps(previews,separators=(',',':'))+';\n')
print(json.dumps({'images':len(previews),'preview_bytes':sum(sizes),'average_bytes':round(sum(sizes)/len(sizes)),'max_bytes':max(sizes),'original_bytes':sum(originals),'manifest_bytes':(root/'previews.js').stat().st_size}))
