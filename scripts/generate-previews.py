"""Regenerate embedded low-resolution WebP previews: python3 scripts/generate-previews.py (Pillow required)."""
from pathlib import Path
from PIL import Image,ImageStat
import base64,io,json
root=Path(__file__).resolve().parents[1]
previews={};sizes=[];originals=[]
for source in sorted((root/'assets').glob('*.webp')):
    if source.stem.endswith('-sm'):continue
    with Image.open(source) as original:
        image=original.convert('RGB');image.thumbnail((64,64),Image.Resampling.LANCZOS)
        data=io.BytesIO();image.save(data,format='WEBP',quality=24,method=6)
        color=tuple(round(v) for v in ImageStat.Stat(image.resize((1,1))).mean)
        previews[source.stem]={'src':'data:image/webp;base64,'+base64.b64encode(data.getvalue()).decode(),'width':image.width,'height':image.height,'color':'#'+''.join(f'{v:02x}' for v in color)}
        sizes.append(len(data.getvalue()));originals.append(source.stat().st_size)
(root/'previews.js').write_text('// Generated by scripts/generate-previews.py. Embedded to avoid a request per placeholder.\nexport const previews = '+json.dumps(previews,separators=(',',':'))+';\n')
print(json.dumps({'images':len(previews),'preview_bytes':sum(sizes),'average_bytes':round(sum(sizes)/len(sizes)),'max_bytes':max(sizes),'original_bytes':sum(originals),'manifest_bytes':(root/'previews.js').stat().st_size}))
